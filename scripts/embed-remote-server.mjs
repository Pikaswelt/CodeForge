#!/usr/bin/env node
// Keep every embedded copy of codeforge-remote-server.mjs in sync with the source file.
//
// The remote server is shipped in three places so a V-Server can be set up without a checkout:
//   - src/components/serverCode.ts      gzip + base64 (the app's "connect a server" command)
//   - codeforge-connect-debian.sh       base64, written to /opt/codeforge-mobile (lines end in LF)
//   - server-setup-codeforge.sh         base64, same target, used by the older setup script
//
// Copies that were edited by hand drifted from the source (one even contained a merge-conflict
// marker), so the server either would not start at all or silently missed features like pairing.
// Run this after changing codeforge-remote-server.mjs:
//   node scripts/embed-remote-server.mjs
//   node scripts/embed-remote-server.mjs --check   (exits 1 when a copy is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(root, 'codeforge-remote-server.mjs');
const serverCodePath = join(root, 'src', 'components', 'serverCode.ts');
const shellTargets = ['codeforge-connect-debian.sh', 'server-setup-codeforge.sh'];

const checkOnly = process.argv.includes('--check');
const source = readFileSync(sourcePath, 'utf8').replace(/\r\n?/g, '\n');
const serverCode = `// Automatically generated by scripts/embed-remote-server.mjs. Do not edit manually.\nexport const REMOTE_SERVER_BASE64 = '${gzipSync(Buffer.from(source, 'utf8')).toString('base64')}';\n`;

// Lone CRs as well as CRLF: the setup script once carried a single stray CR that glued two
// commands into one line, which is exactly the kind of thing that makes bash fail on Linux.
function toLf(text) {
  return text.replace(/\r\n?/g, '\n');
}

function withEmbeddedBase64(fileName, text) {
  const encoded = Buffer.from(source, 'utf8').toString('base64');
  const pattern = /REMOTE_SERVER_B64="[A-Za-z0-9+/=]*"/;
  if (!pattern.test(text)) throw new Error(`${fileName}: REMOTE_SERVER_B64 nicht gefunden.`);
  return text.replace(pattern, `REMOTE_SERVER_B64="${encoded}"`);
}

const changes = [];
const serverCodeCurrent = readFileSync(serverCodePath, 'utf8');
if (serverCodeCurrent !== serverCode) changes.push(serverCodePath);

const shellUpdates = shellTargets.map((fileName) => {
  const path = join(root, fileName);
  const current = readFileSync(path, 'utf8');
  // Shell scripts must be LF-only: a CRLF line ending makes bash fail on the first `if`.
  const next = withEmbeddedBase64(fileName, toLf(current));
  if (next !== current) changes.push(path);
  return { path, next };
});

if (checkOnly) {
  if (changes.length) {
    console.error('Eingebettete Kopien des Remote-Servers sind veraltet:');
    for (const file of changes) console.error(`  - ${file}`);
    console.error('Bitte ausfuehren: node scripts/embed-remote-server.mjs');
    process.exit(1);
  }
  console.log('Alle eingebetteten Remote-Server-Kopien sind aktuell.');
  process.exit(0);
}

writeFileSync(serverCodePath, serverCode);
for (const { path, next } of shellUpdates) writeFileSync(path, next);

if (changes.length) {
  for (const file of changes) console.log(`aktualisiert: ${file}`);
} else {
  console.log('Alles bereits aktuell.');
}
